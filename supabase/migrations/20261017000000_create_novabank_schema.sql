

CREATE TABLE IF NOT EXISTS public.clientes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tipo_documento TEXT NOT NULL,
  documento TEXT NOT NULL UNIQUE,
  nombres TEXT NOT NULL,
  apellidos TEXT NOT NULL,
  fecha_nacimiento TEXT NOT NULL,
  telefono TEXT NOT NULL,
  correo TEXT NOT NULL,
  direccion TEXT NOT NULL,
  estado TEXT NOT NULL DEFAULT 'activo' CHECK (estado IN ('activo', 'inactivo')),
  fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.cuentas (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cliente_id INTEGER NOT NULL REFERENCES public.clientes(id) ON DELETE RESTRICT,
  numero_cuenta TEXT NOT NULL UNIQUE,
  tipo_cuenta TEXT NOT NULL CHECK (tipo_cuenta IN ('Ahorros', 'Corriente', 'Nomina')),
  saldo BIGINT NOT NULL DEFAULT 0 CHECK (saldo >= 0),
  estado TEXT NOT NULL DEFAULT 'activo' CHECK (estado IN ('activo', 'inactivo')),
  fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.transacciones (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cuenta_id INTEGER NOT NULL REFERENCES public.cuentas(id) ON DELETE RESTRICT,
  tipo_transaccion TEXT NOT NULL CHECK (tipo_transaccion IN ('deposito', 'retiro')),
  monto BIGINT NOT NULL CHECK (monto > 0),
  saldo_anterior BIGINT NOT NULL CHECK (saldo_anterior >= 0),
  saldo_resultante BIGINT NOT NULL CHECK (saldo_resultante >= 0),
  descripcion TEXT,
  fecha_hora TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS cuentas_cliente_estado_idx
  ON public.cuentas (cliente_id, estado);

CREATE INDEX IF NOT EXISTS transacciones_cuenta_fecha_idx
  ON public.transacciones (cuenta_id, fecha_hora DESC, id DESC);

ALTER TABLE public.clientes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.cuentas ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.transacciones ENABLE ROW LEVEL SECURITY;

